class KinisiCommands:
    """Public command methods shared by transports implementing protocol v2."""

    def __init__(self):
        """Leave connection state and synchronization to the transport."""

    def _request(self, command: int, payload: bytes, expected_response_length: int) -> bytes:
        """Exchange a command payload and return its matching response payload."""
        raise NotImplementedError("A protocol-v2 transport must implement _request")

    def initialize_motor(self, motor_index: int, is_reversed: bool) -> None:
        """This command initializes a motor and prepares it for use. Rejected with MOTOR_OWNED
        if the motor is currently owned by an active platform (one of its wheels), so
        platform wheels are not reconfigured out from under the platform.

        motor_index: The index of the motor to initialize.
        is_reversed: Whether or not the motor is reversed.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED,
        INIT_REQUIRED.
        """
        payload = struct.pack('<B?', motor_index, is_reversed)
        result = self._request(INITIALIZE_MOTOR, payload, 0)

    def set_motor_speed(self, motor_index: int, pwm: float) -> None:
        """This command sets the speed of the specified motor in PWM. Rejected with MOTOR_OWNED
        if the motor is currently owned by an active platform (one of its wheels); use the
        platform velocity commands to drive platform wheels.

        motor_index: The index of the motor to set the speed for.
        pwm: The speed of the motor.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED,
        MOTOR_NOT_INITIALIZED, INIT_REQUIRED.
        """
        payload = struct.pack('<Bd', motor_index, pwm)
        result = self._request(SET_MOTOR_SPEED, payload, 0)

    def stop_motor(self, motor_index: int) -> None:
        """Coasts the motor to a stop: both H-bridge outputs are driven low, leaving the motor
        terminals open (high impedance) so it free-wheels and spins down gradually under its
        own friction. This also stops that motor's closed-loop speed controller if one is
        running (started via INITIALIZE_MOTOR_CONTROLLER), so the PID loop cannot re-drive
        the motor; to command the motor by target speed again you must re-initialize its
        controller. This is a single-motor command and is ignored if the motor is currently
        owned by an active platform (one of its wheels); to stop a platform, use
        STOP_PLATFORM_CONTROLLER, COAST_PLATFORM or BRAKE_PLATFORM instead. Use STOP_MOTOR
        for a soft, low-stress stop; use BRAKE_MOTOR when you need the motor to hold
        position and stop quickly.

        motor_index: The index of the motor to set the speed for.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED.
        """
        payload = struct.pack('<B', motor_index)
        result = self._request(STOP_MOTOR, payload, 0)

    def brake_motor(self, motor_index: int) -> None:
        """Actively brakes the motor (short brake): both H-bridge outputs are driven high,
        shorting the motor terminals together so the motor's own back-EMF resists rotation
        and it stops quickly and holds position. This also stops that motor's closed-loop
        speed controller if one is running (started via INITIALIZE_MOTOR_CONTROLLER), so the
        PID loop cannot re-drive the motor; to command the motor by target speed again you
        must re-initialize its controller. This is a single-motor command and is ignored if
        the motor is currently owned by an active platform (one of its wheels); to brake a
        platform, use BRAKE_PLATFORM (or STOP_PLATFORM_CONTROLLER / COAST_PLATFORM) instead.
        Use BRAKE_MOTOR for a fast, holding stop; use STOP_MOTOR to let the motor coast
        freely instead.

        motor_index: The index of the motor to set the speed for.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED.
        """
        payload = struct.pack('<B', motor_index)
        result = self._request(BRAKE_MOTOR, payload, 0)

    def initialize_motor_controller(self, motor_index: int, is_reversed: bool, encoder_index: int, is_encoder_reversed: bool, encoder_resolution: float, kp: float, ki: float, kd: float, integral_limit: float) -> None:
        """This command sets the controller for the specified motor. Rejected with MOTOR_OWNED
        if the motor is currently owned by an active platform (one of its wheels), so it
        cannot create a competing controller on a platform wheel.

        motor_index: The index of the motor to set the controller for.
        is_reversed: Whether or not the motor is reversed.
        encoder_index: The index of the encoder to use for the controller.
        is_encoder_reversed: Reverses the encoder counting direction, independently of the
        motor's is_reversed. For closed-loop control the encoder must report a positive
        measured speed when a positive speed is commanded (negative feedback); if the
        controller runs away, flip this flag.
        encoder_resolution: Encoder resolution in ticks per revolution. The value can not be
        negative or zero.
        kp: Proportional constant of PID
        ki: Integral constant of PID
        kd: Derivative constant of PID
        integral_limit: Integral limit of PID controller. The value can not be negative or
        zero. If the value is zero or negative, the integral limit is disabled.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED,
        INIT_REQUIRED.
        """
        payload = struct.pack('<B?B?ddddd', motor_index, is_reversed, encoder_index, is_encoder_reversed, encoder_resolution, kp, ki, kd, integral_limit)
        result = self._request(INITIALIZE_MOTOR_CONTROLLER, payload, 0)

    def set_motor_target_speed(self, motor_index: int, speed: float) -> None:
        """This command sets the target speed for the specified motor in radians. Rejected with
        MOTOR_OWNED if the motor is currently owned by an active platform (one of its
        wheels); use SET_PLATFORM_TARGET_VELOCITY to drive platform wheels.

        motor_index: The index of the motor to set the target velocity for.
        speed: The speed of the motor.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED,
        CONTROLLER_NOT_INITIALIZED, INIT_REQUIRED.
        """
        payload = struct.pack('<Bd', motor_index, speed)
        result = self._request(SET_MOTOR_TARGET_SPEED, payload, 0)

    def reset_motor_controller(self, motor_index: int) -> None:
        """This command resets the closed-loop controller for the specified motor: it clears
        the accumulated PID state (integrator windup, derivative history and internal
        output) and re-zeros the target speed, while keeping the controller running with its
        existing tuning (kp/ki/kd). Use it to recover from integrator windup or to bring a
        motor cleanly to a stop without deleting and re-initializing the controller. No
        effect if no controller is running for that motor, and ignored if the motor is
        currently owned by an active platform (one of its wheels).

        motor_index: The index of the motor to reset the controller for.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED,
        INIT_REQUIRED.
        """
        payload = struct.pack('<B', motor_index)
        result = self._request(RESET_MOTOR_CONTROLLER, payload, 0)

    def get_motor_controller_state(self, motor_index: int) -> MotorControllerState:
        """This command gets the state of the controller for the specified motor.

        motor_index: The index of the motor to get the state for.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, INIT_REQUIRED.
        """
        payload = struct.pack('<B', motor_index)
        result = self._request(GET_MOTOR_CONTROLLER_STATE, payload, MotorControllerState.get_size())
        return MotorControllerState.decode(result)

    def delete_motor_controller(self, motor_index: int) -> None:
        """This command deletes the controller for the specified motor. Rejected with
        MOTOR_OWNED if the motor is currently owned by an active platform (one of its
        wheels); use STOP_PLATFORM_CONTROLLER to stop the platform controller instead.

        motor_index: The index of the motor to delete the controller for.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, MOTOR_OWNED,
        INIT_REQUIRED.
        """
        payload = struct.pack('<B', motor_index)
        result = self._request(DELETE_MOTOR_CONTROLLER, payload, 0)

    def set_controller_frequency(self, frequency: int) -> None:
        """This command sets the global update frequency (in Hz) of the closed-loop motor
        controller task. All motor controllers share a single control loop, so this
        frequency is global and affects every currently running controller as well as any
        created afterwards; the PID sampling time is updated to match. The requested value
        is clamped to the supported range of 1 to 1000 Hz (the 1000 Hz maximum is bounded by
        the 1 ms RTOS tick). The value is then quantized to the 1 ms RTOS tick (period_ms =
        1000 / frequency), so effective frequencies are 1000/N Hz. A value of 0 is invalid
        and ignored. Defaults to 10 Hz (100 ms) at start-up.

        frequency: The controller update frequency in Hz. Valid range 1 to 1000 Hz; values
        outside are clamped, and 0 is ignored.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, INIT_REQUIRED.
        """
        payload = struct.pack('<H', frequency)
        result = self._request(SET_CONTROLLER_FREQUENCY, payload, 0)

    def get_controller_frequency(self) -> int:
        """This command retrieves the current global update frequency (in Hz) of the
        closed-loop motor controller task.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, INIT_REQUIRED.
        """
        payload = struct.pack('<')
        result = self._request(GET_CONTROLLER_FREQUENCY, payload, 2)
        return _unpack_payload('<H', result)[0]

    def initialize_encoder(self, encoder_index: int, encoder_resolution: float, is_reversed: bool) -> None:
        """This command initializes an encoder and prepares it for use.

        encoder_index: The index of the encoder to initialize.
        encoder_resolution: Encoder resolution in ticks per revolution. The value can not be
        negative or zero.
        is_reversed: Whether or not the encoder is reversed.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR, INIT_REQUIRED.
        """
        payload = struct.pack('<Bd?', encoder_index, encoder_resolution, is_reversed)
        result = self._request(INITIALIZE_ENCODER, payload, 0)

    def get_encoder_value(self, encoder_index: int) -> int:
        """This command retrieves the current value of the encoder.

        encoder_index: The index of the encoder to retrieve the value for.

        Controller errors: INVALID_LENGTH, INVALID_ARGUMENT, INTERNAL_ERROR,
        ENCODER_NOT_INITIALIZED, INIT_REQUIRED.
        """
        payload = struct.pack('<B', encoder_index)
        result = self._request(GET_ENCODER_VALUE, payload, 2)
        return _unpack_payload('<H', result)[0]

