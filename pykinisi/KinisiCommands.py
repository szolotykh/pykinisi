def _unpack_payload(fmt: str, payload: bytes) -> tuple:
    """Decode one exact payload rather than accepting a partial or extra frame."""
    expected = struct.calcsize(fmt)
    if len(payload) != expected:
        raise ValueError(f"Expected {expected} payload bytes, received {len(payload)}")
    return struct.unpack(fmt, payload)


class MotorControllerState:
    """The state of the controller for the specified motor.

    motor_index: Index of the motor with the controller.
    kp: Proportional constant of PID
    ki: Integral constant of PID
    kd: Derivative constant of PID
    target_speed: The target speed of the motor.
    current_speed: The current speed of the motor.
    error: The error of the motor.
    output: The output of the motor.
    """

    def __init__(self, motor_index: int, kp: float, ki: float, kd: float, target_speed: float, current_speed: float, error: float, output: float):
        """Store the fields of one controller payload."""
        self.motor_index = motor_index
        self.kp = kp
        self.ki = ki
        self.kd = kd
        self.target_speed = target_speed
        self.current_speed = current_speed
        self.error = error
        self.output = output

    @staticmethod
    def get_size() -> int:
        """Return the encoded payload size, excluding the message header."""
        return 57

    def encode(self) -> bytearray:
        """Encode every field using the packed little-endian wire layout."""
        return bytearray(struct.pack('<bddddddd', self.motor_index, self.kp, self.ki, self.kd, self.target_speed, self.current_speed, self.error, self.output))

    @classmethod
    def decode(cls, payload: bytes) -> 'MotorControllerState':
        """Decode exactly one payload; reject truncation and trailing bytes."""
        return cls(*_unpack_payload('<bddddddd', payload))


